/**
 * MCP Apps build of the canvas (spec section 9): one self-contained HTML file with all
 * JS and CSS inlined (vite-plugin-singlefile), served as the `ui://banana/canvas`
 * resource. A Worker has no filesystem at runtime, so the HTML is written into a TS
 * module (lib/mcp/resources/canvas-html.generated.ts) instead of a dist folder.
 *
 * Run with `npm run build:ui` (also runs as part of `npm run build`).
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import react from "@vitejs/plugin-react";
import { defineConfig, type Plugin } from "vite";
import { viteSingleFile } from "vite-plugin-singlefile";

const root = fileURLToPath(new URL("./", import.meta.url));
const repo = fileURLToPath(new URL("../../", import.meta.url));
const OUT = fileURLToPath(new URL("../../lib/mcp/resources/canvas-html.generated.ts", import.meta.url));

/** Writes the inlined index.html into a TS module. Runs after the singlefile plugin. */
function emitHtmlModule(): Plugin {
  return {
    name: "banana-emit-html-module",
    enforce: "post",
    generateBundle: {
      order: "post",
      handler(_options, bundle) {
        const asset = Object.values(bundle).find((f) => f.type === "asset" && f.fileName.endsWith(".html"));
        if (!asset || asset.type !== "asset") throw new Error("build:ui: no HTML in the bundle");
        const html = typeof asset.source === "string" ? asset.source : new TextDecoder().decode(asset.source);
        if (/<script[^>]+\bsrc=/i.test(html) || /<link[^>]+rel=["']?stylesheet/i.test(html)) {
          throw new Error("build:ui: the canvas HTML must not load external scripts or stylesheets");
        }
        const body = [
          "// Generated by `npm run build:ui` from ui/canvas (vite.config.ts). Do not edit by hand.",
          "// The inline MCP Apps canvas: one HTML file with all JS and CSS inlined.",
          "",
          `export const CANVAS_HTML: string = ${JSON.stringify(html)};`,
          "",
        ].join("\n");
        writeFileSync(OUT, body);
        this.info(`wrote ${OUT} (${Math.round(html.length / 1024)} KB)`);
      },
    },
  };
}

export default defineConfig({
  root,
  // The canvas reads APP_NAME through props; this keeps any stray `process.env` read safe.
  define: {
    "process.env.NODE_ENV": JSON.stringify("production"),
    "process.env.APP_NAME": JSON.stringify(process.env.APP_NAME?.trim() || "Banana"),
  },
  resolve: { alias: { "@": repo.replace(/\/$/, "") } },
  plugins: [react(), viteSingleFile({ removeViteModuleLoader: true }), emitHtmlModule()],
  logLevel: "warn",
  build: {
    // Nothing goes to disk except the generated TS module.
    write: false,
    emptyOutDir: false,
    outDir: "dist",
    target: "es2022",
    cssCodeSplit: false,
    assetsInlineLimit: Number.MAX_SAFE_INTEGER,
    chunkSizeWarningLimit: 4096,
    reportCompressedSize: false,
  },
});
